def scaled_axe(max_height: int) -> str:
    lines = AXE_FULL.strip("\n").split("\n")
    H = len(lines)
    if max_height >= H:
        return "\n".join(lines)
    TH = max(6, max_height)
    W = max(len(l) for l in lines)
    lines = [l.ljust(W) for l in lines]
    sy = H / TH
    TW = max(1, int(W / sy))
    out = []
    for r in range(TH):
        row = ""
        for c in range(TW):
            y0, y1 = int(r * sy), max(int(r * sy) + 1, int((r + 1) * sy))
            x0, x1 = int(c * W / TW), max(int(c * W / TW) + 1, int((c + 1) * W / TW))
            tot = n = 0
            for yy in range(y0, min(y1, H)):
                for xx in range(x0, min(x1, W)):
                    tot += _VAL.get(lines[yy][xx], 0); n += 1
            row += _CH[min(4, round(tot / n)) if n else 0]
        out.append(row.rstrip())
    while out and not out[0].strip(): out.pop(0)
    while out and not out[-1].strip(): out.pop()
    return "\n".join(out)

